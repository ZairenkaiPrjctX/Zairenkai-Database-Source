#!/usr/bin/env python3
"""Propose database changes as a pull request. Used by scheduled/dispatched workflows.

- Only files under database/ may be proposed; anything else aborts.
- Runs `afid database validate --check-index` and `afid policy check` first.
- Creates the commit with the GraphQL createCommitOnBranch mutation, so GitHub signs it.
- Never pushes to the default branch, never force-pushes; skips when there is no diff.
- Dispatches validate.yml on the new branch (PRs opened with GITHUB_TOKEN do not trigger
  workflows by themselves; workflow_dispatch is the documented exception).

Environment: GH_TOKEN, GITHUB_REPOSITORY, GITHUB_SHA (set by Actions), AFID_COMMIT_TRAILER.
Usage: open_data_pr.py --branch-prefix afid/updates --title "..." [--body-file report.md]
"""

from __future__ import annotations

import argparse
import base64
import datetime as dt
import json
import os
import subprocess
import sys
from pathlib import Path

ALLOWED_PREFIX = "database/"


def run(*args: str, check: bool = True) -> str:
    proc = subprocess.run(list(args), capture_output=True, text=True, check=False)
    if check and proc.returncode != 0:
        sys.exit(f"command failed: {' '.join(args[:3])}...: {proc.stderr.strip()[:500]}")
    return proc.stdout


def changed_files() -> tuple[list[str], list[str]]:
    out = run("git", "status", "--porcelain", "-z", "--untracked-files=all")
    added, deleted = [], []
    for entry in filter(None, out.split("\0")):
        status, path = entry[:2], entry[3:]
        if not path.startswith(ALLOWED_PREFIX):
            sys.exit(f"refusing to propose a change outside {ALLOWED_PREFIX}: {path}")
        (deleted if "D" in status else added).append(path)
    return sorted(added), sorted(deleted)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--branch-prefix", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--body-file")
    ap.add_argument("--base", default=os.environ.get("AFID_BASE_BRANCH", ""))
    args = ap.parse_args()

    added, deleted = changed_files()
    if not added and not deleted:
        print("no database changes; no pull request created")
        return 0
    run("afid", "database", "validate", "--check-index")
    run("afid", "policy", "check")

    repo, head = os.environ["GITHUB_REPOSITORY"], os.environ["GITHUB_SHA"]
    base = args.base or json.loads(run("gh", "api", f"repos/{repo}"))["default_branch"]
    stamp = dt.datetime.now(dt.UTC).strftime("%Y%m%d-%H%M%S")
    branch = f"{args.branch_prefix}-{stamp}"
    run(
        "gh", "api", f"repos/{repo}/git/refs", "-f", f"ref=refs/heads/{branch}", "-f", f"sha={head}"
    )

    trailer = os.environ.get("AFID_COMMIT_TRAILER", "").strip()
    body = "Generated by an AFID workflow from verified provider metadata."
    if trailer:
        body += f"\n\n{trailer}"
    mutation = """mutation($input: CreateCommitOnBranchInput!) {
      createCommitOnBranch(input: $input) { commit { oid url } } }"""
    variables = {
        "input": {
            "branch": {"repositoryNameWithOwner": repo, "branchName": branch},
            "expectedHeadOid": head,
            "message": {"headline": args.title, "body": body},
            "fileChanges": {
                "additions": [
                    {"path": p, "contents": base64.b64encode(Path(p).read_bytes()).decode()}
                    for p in added
                ],
                "deletions": [{"path": p} for p in deleted],
            },
        }
    }
    proc = subprocess.run(
        ["gh", "api", "graphql", "--input", "-"],
        input=json.dumps({"query": mutation, "variables": variables}),
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        sys.exit(f"createCommitOnBranch failed: {proc.stderr.strip()[:500]}")
    commit = json.loads(proc.stdout)["data"]["createCommitOnBranch"]["commit"]
    print(f"commit {commit['oid']} on {branch}")

    pr_body = Path(args.body_file).read_text() if args.body_file else body
    pr_body += f"\n\nFiles: {len(added)} added/changed, {len(deleted)} deleted."
    url = run(
        "gh",
        "pr",
        "create",
        "--repo",
        repo,
        "--base",
        base,
        "--head",
        branch,
        "--title",
        args.title,
        "--body",
        pr_body,
    ).strip()
    print(f"opened {url}")
    run("gh", "workflow", "run", "validate.yml", "--repo", repo, "--ref", branch, check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
